"""Turn the cached CSVs into `reports/results.md` and the figures.

Separating this from evaluation means the written report can be regenerated,
reworded or re-styled without touching a model — and that nothing in it can
drift away from the numbers, because there is no second copy of them.
"""

from __future__ import annotations

import json
import logging

import pandas as pd

from garde_fou.evaluation.runner import load_scores
from garde_fou.paths import REPORTS
from garde_fou.reporting.plots import DETECTOR_LABELS, SET_LABELS, render_all

log = logging.getLogger(__name__)

SET_ORDER = ("test_in", "test_ood", "test_fr", "test_adv")


def _read(name: str) -> pd.DataFrame | None:
    path = REPORTS / name
    if not path.exists():
        log.warning("%s missing, skipping the sections that need it", name)
        return None
    return pd.read_csv(path)


def _pct(v: float) -> str:
    return "—" if pd.isna(v) else f"{v * 100:.1f}%"


def detection_table(summary: pd.DataFrame) -> str:
    pivot = summary.pivot_table(index="detector", columns="eval_set", values="recall")
    pivot = pivot.reindex(
        [d for d in DETECTOR_LABELS if d in pivot.index],
        columns=[c for c in SET_ORDER if c in pivot.columns],
    )
    header = "| detector | " + " | ".join(SET_LABELS[c] for c in pivot.columns) + " |"
    rule = "|---" * (len(pivot.columns) + 1) + "|"
    lines = [header, rule]
    for detector, row in pivot.iterrows():
        cells = " | ".join(_pct(row[c]) for c in pivot.columns)
        lines.append(f"| `{detector}` | {cells} |")
    return "\n".join(lines)


def fpr_table(summary: pd.DataFrame) -> str:
    lines = [
        "| detector | legitimate requests blocked per 1,000 (cross-dataset) |",
        "|---|---|",
    ]
    ood = summary[summary.eval_set == "test_ood"].set_index("detector")
    for detector in [d for d in DETECTOR_LABELS if d in ood.index]:
        lines.append(f"| `{detector}` | {ood.loc[detector, 'blocked_per_1000_legit']:.1f} |")
    return "\n".join(lines)


def robustness_table(robustness: pd.DataFrame, detector: str) -> str:
    part = robustness[robustness.detector == detector].sort_values("youden")
    lines = [
        "| rewrite | family | fidelity | attacks blocked | legitimate blocked | J | AUC |",
        "|---|---|---|---|---|---|---|",
    ]
    for _, row in part.iterrows():
        lines.append(
            f"| `{row['mutator']}` | {row['family']} | {row['fidelity']} | "
            f"{_pct(row['recall'])} | {_pct(row['fpr'])} | "
            f"{row['youden']:+.2f} | {row['roc_auc']:.3f} |"
        )
    return "\n".join(lines)


def recalibration_table(recal: pd.DataFrame) -> str:
    lines = [
        "| detector | threshold estimated on | attacks blocked | legitimate blocked |",
        "|---|---|---|---|",
    ]
    for _, row in recal.iterrows():
        lines.append(
            f"| `{row['detector']}` | {row['threshold_from']} | "
            f"{_pct(row['recall'])} | {_pct(row['fpr'])} |"
        )
    return "\n".join(lines)


def latency_table(latency: pd.DataFrame) -> str:
    lines = ["| detector | kind | p50 | p95 |", "|---|---|---|---|"]
    for _, row in latency.iterrows():
        lines.append(
            f"| `{row['detector']}` | {row['kind']} | {row['p50_ms']:.2f} ms | {row['p95_ms']:.2f} ms |"
        )
    return "\n".join(lines)


def build_report() -> list[str]:
    summary = _read("summary.csv")
    if summary is None:
        raise FileNotFoundError("run `garde-fou eval` before `garde-fou report`")
    robustness = _read("robustness.csv")
    latency = _read("latency.csv")
    recal = _read("recalibration.csv")
    scores = load_scores()

    target = "cascade" if "cascade" in set(summary.detector) else summary.detector.iloc[0]
    figures = render_all(
        summary,
        robustness if robustness is not None else pd.DataFrame(),
        scores,
        latency,
        robustness_detector=target,
    )

    manifest_path = REPORTS.parent / "data" / "processed" / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}

    parts = [
        "# Results",
        "",
        "Generated by `garde-fou report`. Every number comes from "
        "`reports/scores.parquet`; nothing here is typed by hand.",
        "",
        "## Detection at a 1% false-positive budget",
        "",
        "Share of attacks blocked. The threshold is calibrated **once** on the "
        "validation split at a 1% false-positive rate, then held fixed across "
        "every test set — which is the only way the comparison means anything.",
        "",
        detection_table(summary),
        "",
        "![Generalisation](figures/generalisation.png)",
        "",
        "## Cost on legitimate traffic",
        "",
        fpr_table(summary),
        "",
        "## Robustness to cheap rewrites",
        "",
        f"Per-rewrite detection for `{target}`, same threshold, on held-out attacks "
        "**and** held-out benign prompts put through the same rewrite. `none` is the "
        "untouched control. `J` is Youden's index (attacks blocked − legitimate blocked): "
        "it is near zero when the detector is firing on the rewrite itself rather than on "
        "the attack, which is why recall alone is not reported here.",
        "",
        robustness_table(robustness, target) if robustness is not None else "_not available_",
        "",
        f"![Robustness](figures/robustness-{target}.png)",
        "",
        "## Latency, measured at batch size 1 on CPU",
        "",
        latency_table(latency) if latency is not None else "_run `garde-fou bench`_",
        "",
        "![Latency against detection](figures/pareto.png)",
        "",
        "## Does the operating point survive real traffic?",
        "",
        "The threshold is re-estimated from held-out **benign French prompts only** — no "
        "attack labels, nothing retrained — and the French test set is then scored with "
        "it. A detector whose two rows differ was never delivering the recall its "
        "validation-calibrated number advertised.",
        "",
        recalibration_table(recal) if recal is not None else "_run `garde-fou recalibrate`_",
        "",
        "## ROC",
        "",
        "![ROC](figures/roc.png)",
        "",
        "## Dataset sizes",
        "",
        "| set | rows | attacks | benign | sources |",
        "|---|---|---|---|---|",
    ]
    for name, info in manifest.items():
        if name.startswith("pool_"):
            continue
        parts.append(
            f"| `{name}` | {info['rows']} | {info['injection']} | {info['benign']} | "
            f"{', '.join(info['sources'])} |"
        )
    parts.append("")

    out = REPORTS / "results.md"
    out.write_text("\n".join(parts))
    return [str(out.relative_to(REPORTS.parent)), *figures]
